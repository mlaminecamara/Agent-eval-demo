"""Rebuild the README results section from the result files.

    make report   ->  python -m evals.compare && python -m evals.report

Replaces everything between the RESULTS markers in README.md with the comparison generated
by evals.compare (evals/results/comparison.md). The README never contains a number that is
not in that file. Without the markers, nothing is written.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from agent_eval.config import PROJECT_ROOT

README = PROJECT_ROOT / "README.md"
COMPARISON = PROJECT_ROOT / "evals" / "results" / "comparison.md"
START = "<!-- RESULTS:START (generated by `make report`, do not edit) -->"
END = "<!-- RESULTS:END -->"


def results_block(comparison_md: str) -> str:
    """The comparison without its title, one heading level down to sit under a README '##'."""
    lines = comparison_md.strip().splitlines()
    if lines and lines[0].startswith("# "):
        lines = lines[1:]
    body = "\n".join("#" + line if line.startswith("## ") else line for line in lines).strip()
    source = "Source: [`evals/results/comparison.md`](evals/results/comparison.md)."
    return f"{START}\n\n{body}\n\n{source}\n\n{END}"


def update_readme(readme: str, comparison_md: str) -> str:
    if START not in readme or END not in readme:
        raise ValueError("README has no RESULTS markers")
    before, rest = readme.split(START, 1)
    _, after = rest.split(END, 1)
    return before + results_block(comparison_md) + after


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--readme", type=Path, default=README)
    p.add_argument("--comparison", type=Path, default=COMPARISON)
    args = p.parse_args(argv)
    if not args.comparison.exists():
        print(f"{args.comparison} not found: run `python -m evals.compare` first.")
        return 1
    readme = args.readme.read_text(encoding="utf-8")
    try:
        updated = update_readme(readme, args.comparison.read_text(encoding="utf-8"))
    except ValueError as exc:
        print(f"{args.readme}: {exc}; add the markers where the results should go:\n{START}\n{END}")
        return 1
    args.readme.write_text(updated, encoding="utf-8")
    print(f"Updated the results section of {args.readme}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
